source(file.path(testthat::test_path(), "..", "fixtures", "helper.R"))

test_that("progress records are atomic, bounded, side-local, and retain final timings", {

  project <- tempfile("progress-project-"); dir.create(project)
  p <- project
  progress_set_step(p, "ADSL", "ADSL.AGE", "primary", "inputs", list("DM.AGE"))
  progress_event(p, "ADSL", "ADSL.AGE", "primary", "reading DM.AGE\nsecond line")
  progress_set_step(p, "ADSL", "ADSL.AGE", "primary", "writing")
  Sys.sleep(0.02)
  progress_set_step(p, "ADSL", "ADSL.AGE", "primary", "running")
  rec <- progress_read(p, "ADSL", "ADSL.AGE", "primary")
  expect_equal(rec$step, "running")
  expect_equal(unlist(rec$inputs), "DM.AGE")
  expect_equal(unlist(rec$events), "reading DM.AGE second line")
  expect_true(rec$step_timings$writing >= 0)
  expect_null(progress_read(p, "ADSL", "ADSL.AGE", "validation"))
  for (i in seq_len(40)) progress_event(p, "ADSL", "ADSL.AGE", "primary", paste("event", i))
  expect_length(progress_read(p, "ADSL", "ADSL.AGE", "primary")$events, 30)
  progress_finish(p, "ADSL", "ADSL.AGE", "primary", "object 'AGE' not found")
  rec <- progress_read(p, "ADSL", "ADSL.AGE", "primary")
  expect_true(rec$done)
  expect_match(rec$error, "AGE")
  expect_true(is.list(rec$step_timings))
  progress_finish(p, "ADSL", "ADSL.AGE", "primary")
  rec <- progress_read(p, "ADSL", "ADSL.AGE", "primary")
  expect_true(rec$done)
  expect_null(rec$error)
  expect_true(is.list(rec$step_timings))
  progress_event(p, "ADSL", "ADSL.AGE", "primary", "old run event")
  progress_set_step(p, "ADSL", "ADSL.AGE", "primary", "writing")
  rec <- progress_read(p, "ADSL", "ADSL.AGE", "primary")
  expect_false(rec$done)
  expect_length(rec$events, 0)
  expect_null(rec$error)
})
